//! Writes `fixtures/encodings/commitments.json`: inputs and the commitments Rust computes for
//! them. Solidity (`contracts/test/Encodings.t.sol`) and TypeScript (`ts/check-encodings.ts`)
//! recompute every value and must match. Deterministic: rerunning must not change the file.

use alloy_primitives::{B256, U256, address, hex, keccak256};
use alloy_sol_types::SolValue;
use channel_types::*;
use serde_json::{Value, json};

fn h(b: impl AsRef<[u8]>) -> String {
    hex::encode_prefixed(b)
}

fn main() {
    let settlement = address!("5e77100000000000000000000000000000000001");
    let executor = address!("e7ec000000000000000000000000000000000002");
    let alice = address!("a11ce00000000000000000000000000000000000");
    let bob = address!("b0b0000000000000000000000000000000000000");
    let l1_chain_id = 11155111u64;
    let salt = keccak256(b"fixture-salt");

    let anchor = L1Anchor {
        chainId: U256::from(l1_chain_id),
        blockNumber: 12_000_000,
        blockHash: keccak256(b"anchor-block"),
        stateRoot: keccak256(b"anchor-state"),
    };
    let policy = ChannelPolicy {
        anchorConfirmation: ConfirmationPolicy::Finalized as u8,
        maxAnchorLag: 64,
        challengeWindow: 7 * 24 * 3600,
    };
    let profile = ExecutionProfile {
        rollupId: keccak256(b"rollup"),
        kind: ExecutionProfileKind::MockLocal as u8,
        genesisHash: keccak256(b"genesis"),
        programHash: keccak256(b"program"),
        forkSchemaHash: keccak256(b"fork"),
        daSchemaHash: keccak256(b"da"),
        executorCodeHash: keccak256(b"executor-code"),
    };
    let cid = channel_id(l1_chain_id, settlement, alice, salt);
    let proot = participant_root(&[alice, bob]).unwrap();
    let terms = ChannelTerms {
        channelId: cid,
        rollupId: profile.rollupId,
        settlementContract: settlement,
        executor,
        moduleCodeHash: keccak256(b"split-module"),
        participantRoot: proot,
        policyHash: policy.hash(),
        closeDeadline: 1_800_000_000,
    };
    let request = FinalRequest {
        channelId: cid,
        termsHash: terms.hash(),
        anchorId: anchor.id(),
        policyHash: policy.hash(),
        executionProfileHash: profile_hash(&profile).unwrap(),
        inputHash: keccak256(b"split-input"),
        nonce: 1,
    };

    let req_enc = request.abi_encode();
    let mut trailing = req_enc.clone();
    trailing.push(0);
    let mut dirty = req_enc.clone();
    let n = dirty.len();
    dirty[n - 32] = 1;

    let out: Value = json!({
        "_comment": "Generated by `cargo run -p channel-types --bin gen-fixtures`. Do not edit.",
        "l1ChainId": l1_chain_id,
        "settlement": settlement,
        "opener": alice,
        "salt": salt,
        "participants": [alice, bob],
        "channelId": cid,
        "participantRoot": proot,
        "anchor": {
            "chainId": h(B256::from(anchor.chainId)),
            "blockNumber": anchor.blockNumber,
            "blockHash": anchor.blockHash,
            "stateRoot": anchor.stateRoot,
            "encoded": h(anchor.abi_encode()),
            "id": anchor.id(),
        },
        "policy": {
            "anchorConfirmation": policy.anchorConfirmation, "maxAnchorLag": policy.maxAnchorLag,
            "challengeWindow": policy.challengeWindow, "hash": policy.hash(),
        },
        "profile": {
            "rollupId": profile.rollupId, "kind": profile.kind, "genesisHash": profile.genesisHash,
            "programHash": profile.programHash, "forkSchemaHash": profile.forkSchemaHash,
            "daSchemaHash": profile.daSchemaHash, "executorCodeHash": profile.executorCodeHash,
            "hash": profile_hash(&profile).unwrap(),
        },
        "terms": {
            "channelId": terms.channelId, "rollupId": terms.rollupId, "settlementContract": terms.settlementContract,
            "executor": terms.executor, "moduleCodeHash": terms.moduleCodeHash, "participantRoot": terms.participantRoot,
            "policyHash": terms.policyHash, "closeDeadline": terms.closeDeadline,
            "encoded": h(terms.abi_encode()), "hash": terms.hash(),
        },
        "request": {
            "channelId": request.channelId, "termsHash": request.termsHash, "anchorId": request.anchorId,
            "policyHash": request.policyHash, "executionProfileHash": request.executionProfileHash,
            "inputHash": request.inputHash, "nonce": request.nonce,
            "encoded": h(&req_enc),
            "domainSeparator": domain(l1_chain_id, settlement).separator(),
            "signingHash": request.signing_hash(l1_chain_id, settlement),
        },
        "malformedRequests": {
            "truncated": h(&req_enc[..req_enc.len() - 1]),
            "trailingByte": h(&trailing),
            "dirtyNoncePadding": h(&dirty),
        },
    });
    for (name, bad) in out["malformedRequests"].as_object().unwrap() {
        let bytes = hex::decode(bad.as_str().unwrap()).unwrap();
        assert!(
            decode_strict::<FinalRequest>(&bytes).is_err(),
            "{name} must be rejected"
        );
    }
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../fixtures/encodings/commitments.json"
    );
    std::fs::write(path, serde_json::to_string_pretty(&out).unwrap() + "\n").unwrap();
    println!("wrote {path}");
}
