//! Deterministic receipt-trie fixtures (`fixtures/receipts/block-130.json`) for the later
//! Solidity receipt verifier (M2). 130 receipts so indices cross the RLP key boundaries
//! (0 → `0x80`, 1..=127 → one byte, 128+ → `0x81 ..`), every receipt type the envelope
//! knows, failed and successful receipts, and `ChannelOutcome` logs at chosen indices.
//!
//! Regenerate with `UPDATE_FIXTURES=1 cargo test -p channel-receipts`; the test otherwise
//! fails if the file differs from what the code produces.

use alloy_consensus::{Eip658Value, Header, Receipt, ReceiptEnvelope, ReceiptWithBloom};
use alloy_eips::eip2718::Encodable2718;
use alloy_primitives::{Address, B256, Bytes, Log, address, hex, keccak256};
use alloy_sol_types::{SolEvent, sol};
use serde_json::{Value, json};

use crate::{receipt_proof, receipts_root};

sol! {
    /// Emitted by the L2 `ChannelExecutor` (PROJECT.md §5.4).
    event ChannelOutcome(bytes32 indexed channelId, bytes32 indexed requestHash, bytes32 anchorId, bytes32 policyHash, bytes32 outcomeHash);
}

pub const EXECUTOR: Address = address!("e7ec000000000000000000000000000000000002");
pub const IMPOSTOR: Address = address!("0000000000000000000000000000000000000bad");
pub const RECEIPT_COUNT: usize = 130;
/// (index, emitter) of receipts carrying a ChannelOutcome log.
pub const OUTCOME_AT: [(usize, Address); 3] = [(2, EXECUTOR), (129, EXECUTOR), (7, IMPOSTOR)];
/// Indices whose proofs are written out.
pub const PROVEN: [usize; 7] = [0, 1, 2, 7, 127, 128, 129];

pub fn outcome_log(emitter: Address, i: usize) -> Log {
    let tag = |s: &str| keccak256(format!("{s}-{i}"));
    let ev = ChannelOutcome {
        channelId: tag("channel"),
        requestHash: tag("request"),
        anchorId: tag("anchor"),
        policyHash: tag("policy"),
        outcomeHash: tag("outcome"),
    };
    Log {
        address: emitter,
        data: ev.encode_log_data(),
    }
}

pub fn receipt(i: usize) -> ReceiptEnvelope {
    let mut logs = vec![Log::new_unchecked(
        Address::left_padding_from(&(i as u64 + 1).to_be_bytes()),
        vec![keccak256(format!("topic-{i}"))],
        Bytes::from(vec![i as u8; i % 5]),
    )];
    if let Some((_, emitter)) = OUTCOME_AT.iter().find(|(j, _)| *j == i) {
        logs.push(outcome_log(*emitter, i));
    }
    let r = Receipt {
        status: Eip658Value::Eip658(i % 7 != 3),
        cumulative_gas_used: 21_000 * (i as u64 + 1),
        logs,
    };
    let rb = ReceiptWithBloom::from(r);
    match i % 5 {
        0 => ReceiptEnvelope::Legacy(rb),
        1 => ReceiptEnvelope::Eip2930(rb),
        2 => ReceiptEnvelope::Eip1559(rb),
        3 => ReceiptEnvelope::Eip4844(rb),
        _ => ReceiptEnvelope::Eip7702(rb),
    }
}

pub fn encoded_receipts() -> Vec<Bytes> {
    (0..RECEIPT_COUNT)
        .map(|i| Bytes::from(receipt(i).encoded_2718()))
        .collect()
}

/// An L2 header committing to the receipts.
pub fn header(receipts_root: B256) -> Header {
    Header {
        parent_hash: keccak256("l2-parent"),
        number: 1,
        gas_limit: 30_000_000,
        gas_used: 21_000 * RECEIPT_COUNT as u64,
        timestamp: 1_800_000_000,
        state_root: keccak256("l2-state"),
        receipts_root,
        base_fee_per_gas: Some(7),
        ..Default::default()
    }
}

pub fn generate() -> Value {
    let enc = encoded_receipts();
    let root = receipts_root(&enc);
    let h = header(root);
    let raw = Bytes::from(alloy_rlp::encode(&h));
    let cases: Vec<Value> = PROVEN
        .iter()
        .map(|&i| {
            let r = receipt(i);
            let outcome = OUTCOME_AT
                .iter()
                .find(|(j, _)| *j == i)
                .map(|(_, e)| json!({ "logIndex": 1, "emitter": e }));
            json!({
                "index": i,
                "key": hex::encode_prefixed(crate::index_key(i)),
                "type": r.tx_type() as u8,
                "status": r.status(),
                "receipt": enc[i],
                "proof": receipt_proof(&enc, i).unwrap(),
                "outcome": outcome,
            })
        })
        .collect();
    json!({
        "_comment": "Generated by channel-receipts (UPDATE_FIXTURES=1 cargo test -p channel-receipts). Do not edit.",
        "executor": EXECUTOR,
        "channelOutcomeTopic": ChannelOutcome::SIGNATURE_HASH,
        "header": { "raw": raw, "hash": keccak256(&raw), "receiptsRoot": root },
        "receipts": enc,
        "cases": cases,
    })
}
